-- SQL Basics · Exercise 7 — T2/D: NOT a IS NULL AND NOT a IS NOT NULL

SELECT a,
a IS NULL AS "a IS NULL", NOT a IS NULL AS "NOT a IS NULL",
NOT a IS NOT NULL AS "NOT a IS NOT NULL",
NOT a IS NULL AND NOT a IS NOT NULL AS "NOT a IS NULL AND NOT a IS NOT NULL"
FROM (VALUES (ROW(TRUE)), (ROW(FALSE)), (ROW(NULL)), (ROW(1, NULL))) AS t(a);
